"""Strict additive order types of five goods (k4/ksens.md §8): every sign vector
    sigma(v) = ( sign(v(S) - v(T)) : {S, T} disjoint nonempty subsets of the five goods )    (90 pairs)
with no zero entry that some positive additive v realizes, i.e. the chambers of the arrangement v(S) = v(T) inside the
open orthant.  Each is stored with a small integer representative.  The k = 3, 4 analogue is k4/order_types.py (its
strict types: 12 and 336).

Completeness (the argument of k4/order_types.py, at k = 5).  Add the five coordinate hyperplanes.  The closure of a
chamber is a pointed cone generated by extreme rays, each a 1-dimensional face: the null vector of four independent
rows with entries in {-1, 0, 1}, whose coordinates are 4 x 4 minors of such rows, at most 2^4 = 16 in absolute value
(Hadamard: each row has norm at most 2).  The sum of five independent extreme rays lies in the open simplicial cone they
span, hence in the chamber, and has coordinates at most 5 * 16 = 80.  So every chamber has an integer point in
[1, 80]^5.  With the ranking fixed (v_0 > v_1 > ... > v_4; a chamber has distinct coordinates), it suffices to scan
the C(80, 5) = 24,040,016 strictly decreasing tuples; the other rankings are the 120 permutations.  A smaller grid
(B = 40) is run as well; both must give the same count.

    python3 k4/ksens/types5.py [B ...]      writes results/k4_ksens/types5.json.gz for the largest B"""
import sys, itertools, json, gzip, time
import numpy as np

K = 5


def pairs(k=K):
    out = []
    for S in range(1, 1 << k):
        for T in range(S + 1, 1 << k):
            if S & T == 0: out.append((S, T))
    return out


def decreasing(B, k=K):
    """all strictly decreasing k-tuples in [1, B], in chunks (numpy)"""
    buf = []
    for t in itertools.combinations(range(B, 0, -1), k):
        buf.append(t)
        if len(buf) == 1 << 20: yield np.array(buf, dtype=np.int64); buf = []
    if buf: yield np.array(buf, dtype=np.int64)


def scan(B):
    P = pairs(); masks = np.array([[S >> g & 1 for g in range(K)] for S in range(1 << K)], dtype=np.int64)
    Si = np.array([S for S, T in P]); Ti = np.array([T for S, T in P]); seen = {}
    for X in decreasing(B):
        sums = X @ masks.T                                   # (N, 32): v(S) for every subset S
        D = sums[:, Si] - sums[:, Ti]                        # (N, 90)
        strict = (D != 0).all(1); X, D = X[strict], D[strict]
        bits = np.packbits(D > 0, axis=1)                    # sign vector, packed
        keys, idx = np.unique(bits, axis=0, return_index=True)
        for kb, i in zip(map(bytes, keys), idx):
            v = tuple(int(x) for x in X[i]); key = (max(v), sum(v), v)
            if kb not in seen or key < seen[kb][0]: seen[kb] = (key, v)
    return {kb: kv[1] for kb, kv in seen.items()}


if __name__ == '__main__':
    Bs = [int(a) for a in sys.argv[1:]] or [40, 80]; t0 = time.time(); res = {}
    print('$ python3 k4/ksens/types5.py', *Bs, flush=True)
    for B in Bs:
        res[B] = scan(B)
        print('B = %d: %d strict types with the ranking v0 > v1 > v2 > v3 > v4 (%.0f s)' % (B, len(res[B]), time.time() - t0),
              flush=True)
    top = res[max(Bs)]
    assert all(set(res[B]) <= set(top) for B in Bs), 'a smaller grid found a type the largest did not'
    reps = sorted(top.values())
    print('largest representative coordinate:', max(max(v) for v in reps))
    json.dump({'k': K, 'grid': max(Bs), 'ranking': 'v0 > v1 > v2 > v3 > v4', 'reps': reps},
              gzip.open('results/k4_ksens/types5.json.gz', 'wt'))
    print('wrote results/k4_ksens/types5.json.gz (%d representatives; with the 120 rankings %d types)' % (len(reps), 120 * len(reps)))
